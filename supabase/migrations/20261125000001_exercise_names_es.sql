SET name_es = m.name_es,
    category = CASE m.categoria_en
      WHEN 'chest' THEN 'Pecho'
      WHEN 'back' THEN 'Espalda'
      WHEN 'shoulders' THEN 'Hombro'
      WHEN 'neck' THEN 'Cuello'
      WHEN 'upper arms' THEN 'Brazo'
      WHEN 'lower arms' THEN 'Antebrazo'
      WHEN 'waist' THEN 'Core'
      WHEN 'upper legs' THEN 'Pierna'
      WHEN 'lower legs' THEN 'Pantorrilla'
      WHEN 'cardio' THEN 'Cardio'
      ELSE e.category
    END,
    body_part = m.categoria_en,
    muscle_group = m.parte_del_cuerpo
FROM exercise_name_migration m
WHERE e.external_id = m.external_id;

